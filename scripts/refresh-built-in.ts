// Refreshes the built-in fallback tables (src/engine/built-in-prices.ts) from a
// us-east-1 price file made by build-prices.ts. The set of types stays the same
// curated list; values come from AWS's list, and types AWS no longer lists are dropped.
//
//   node scripts/build-prices.ts --regions us-east-1 --out .prices-work/out
//   node scripts/refresh-built-in.ts .prices-work/out/us-east-1.json

import fs from 'node:fs';
import * as current from '../src/engine/built-in-prices.ts';
import type { PriceBook } from '../src/engine/types.ts';

const book = JSON.parse(fs.readFileSync(process.argv[2], 'utf8')) as PriceBook;
if (book.region !== 'us-east-1') throw new Error('The built-in tables are us-east-1 prices; give the us-east-1 file.');
const month = new Date(book.asOf).toLocaleString('en-US', { month: 'long', year: 'numeric', timeZone: 'UTC' });

function table(name: string, keys: string[], lookup: (k: string) => number | undefined): string {
  const rows: string[] = [];
  let family = '';
  let line: string[] = [];
  const flush = () => { if (line.length) rows.push(`  ${line.join(' ')}`); line = []; };
  for (const k of keys) {
    const v = lookup(k);
    if (v === undefined) { console.log(`dropped ${k} (not in AWS's list)`); continue; }
    const f = k.slice(0, k.lastIndexOf('.'));
    if (f !== family || line.length === 3) flush();
    family = f;
    line.push(`'${k}': ${v},`);
  }
  flush();
  return `export const ${name}: Record<string, number> = {\n${rows.join('\n')}\n};\n`;
}

const ebs = Object.entries(current.EBS).map(([k, v]) => {
  const merged = { ...v, storage: book.ebs?.[k] ?? v.storage };
  return `  '${k}': ${JSON.stringify(merged).replace(/"(\w+)":/g, '$1: ').replace(/,/g, ', ').replace('{', '{ ').replace('}', ' }')},`;
});

const out = `// Built-in fallback prices: USD/hour, on-demand Linux, us-east-1 (AWS list prices, ${month}).
// Used only when the daily price file for a region can't be downloaded.
// Generated by scripts/refresh-built-in.ts from AWS's public price list; edit the script, not this file.
export const BUILT_IN_PRICE_DATE = '${month}';

${table('EC2', Object.keys(current.EC2), (k) => book.ec2[k])}
// MySQL / PostgreSQL / MariaDB, Single-AZ (PostgreSQL price; MySQL and MariaDB are within a few percent)
${table('RDS', Object.keys(current.RDS), (k) => book.rds[k]?.postgres)}
${table('ELASTICACHE', Object.keys(current.ELASTICACHE), (k) => book.elasticache[k])}
${table('REDSHIFT', Object.keys(current.REDSHIFT), (k) => book.redshift[k])}
// Notebook instances
${table('SAGEMAKER', Object.keys(current.SAGEMAKER), (k) => book.sagemaker[k])}
// EBS, per GB-month; iops and throughput are per unit-month above gp3's included amounts
export const EBS: Record<string, { storage: number; iops?: number; throughput?: number }> = {
${ebs.join('\n')}
};

// Regional price multipliers relative to us-east-1, for the built-in tables only.
export const REGION_MULTIPLIER: Record<string, number> = {
${Object.entries(current.REGION_MULTIPLIER).map(([k, v]) => `  '${k}': ${v},`).join('\n')}
};
`;
fs.writeFileSync('src/engine/built-in-prices.ts', out);
console.log(`built-in tables refreshed to ${month}`);
