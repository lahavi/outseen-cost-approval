// Bundles the hook and the estimate CLI into dist/ (committed, so the plugin
// needs no install step), and writes the skill's offline price reference.
import { build } from 'esbuild';
import fs from 'node:fs';

const common = { bundle: true, platform: 'node', target: 'node20', format: 'cjs', minify: true, legalComments: 'none' };
await build({ ...common, entryPoints: ['src/hook.ts'], outfile: 'dist/hook.cjs' });
await build({ ...common, entryPoints: ['src/cli.ts'], outfile: 'dist/cli.cjs' });

const prices = await import('../src/engine/built-in-prices.ts');
const table = (title, rows) => [`## ${title}`, '', '| Type | USD/hour | About USD/month |', '| --- | --- | --- |',
  ...Object.entries(rows).map(([k, v]) => `| ${k} | ${v} | ${Math.round(v * 730)} |`), ''].join('\n');
const md = [
  '# AWS on-demand list prices (offline reference)',
  '',
  `us-east-1, Linux, ${prices.BUILT_IN_PRICE_DATE}. Generated by scripts/build.mjs from src/engine/built-in-prices.ts; do not edit.`,
  'Use this only when the estimate CLI cannot be run. Other regions usually cost 0–20% more (sa-east-1 about 35% more).',
  'A month is 730 hours.',
  '',
  table('EC2 instances', prices.EC2),
  table('RDS instances (MySQL, PostgreSQL, MariaDB; Single-AZ. Multi-AZ is double)', prices.RDS),
  table('ElastiCache nodes', prices.ELASTICACHE),
  table('Redshift nodes', prices.REDSHIFT),
  table('SageMaker notebook instances', prices.SAGEMAKER),
  '## EBS volumes (USD per GB-month)',
  '',
  '| Type | Storage | Extra |',
  '| --- | --- | --- |',
  ...Object.entries(prices.EBS).map(([k, v]) => `| ${k} | ${v.storage} | ${v.iops ? `${v.iops}/IOPS-month${k === 'gp3' ? ' above 3,000' : ''}` : ''}${v.throughput ? `, ${v.throughput}/MB/s-month above 125` : ''} |`),
  '',
  '## Other',
  '',
  '- NAT gateway: 0.045/hour (about 33/month) plus 0.045 per GB processed.',
  '- EKS cluster: 0.10/hour (about 73/month), plus its worker nodes at EC2 prices.',
  '- RDS storage: 0.115 per GB-month (gp2/gp3); io1 0.125 per GB-month plus 0.10 per IOPS-month.',
  '- Aurora Serverless v2: 0.12 per ACU-hour. Capacity scales with load, so any monthly figure is an assumption.',
  '- S3: 0.023 per GB-month (Standard). The bucket itself is free; cost depends on what is stored.',
  '',
].join('\n');
fs.writeFileSync('skills/aws-cost-estimate/reference/prices.md', md);

for (const f of ['dist/hook.cjs', 'dist/cli.cjs']) {
  const kib = fs.statSync(f).size / 1024;
  console.log(`${f}: ${kib.toFixed(1)} KiB`);
  if (kib > 256) { console.error(`${f} is over 256 KiB (directory review holds larger files)`); process.exitCode = 1; }
}
